import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";

test("stable account card, advanced filters, profile and password changes", async ({ page }, testInfo) => {
  const username = `ux_${randomUUID().replaceAll("-", "").slice(0, 16)}`;
  const password = "Disposable-ux-password-2026";
  await page.goto("/");
  await expect(page.getByLabel("Username")).toBeEnabled();
  await page.screenshot({ path: testInfo.outputPath("sign-in-desktop.png"), fullPage: true });
  const before = await page.locator(".account-card").boundingBox();
  await page.getByRole("group", { name: "Account options" }).getByRole("button", { name: "Create account", exact: true }).click();
  const after = await page.locator(".account-card").boundingBox();
  expect(Math.abs(before!.height - after!.height)).toBeLessThan(1);
  expect(Math.abs(before!.width - after!.width)).toBeLessThan(1);
  await page.getByLabel("Username").fill(username);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.locator("form").getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Account created.");
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.locator("form").getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("button", { name: "Profile", exact: true })).toBeVisible();
  const signout = await page.getByRole("button", { name: "Sign out", exact: true }).boundingBox();
  expect(signout!.y).toBeLessThan(88);
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath("workspace-desktop.png"), fullPage: true });
  await page.getByLabel("Per page").selectOption("12");
  await expect(page.getByRole("article")).toHaveCount(12);
  await page.getByRole("button", { name: "Next", exact: true }).click();
  await expect(page.getByRole("article").first()).toHaveAttribute("aria-label", "weedle");
  await page.getByText(/^Filters/).click();
  await page.getByRole("checkbox", { name: "fire", exact: true }).check();
  await page.getByRole("checkbox", { name: "water", exact: true }).check();
  await expect(page.getByRole("article")).toHaveCount(6);
  await page.getByLabel("Type matching").selectOption("all");
  await expect(page.getByText("No Pokémon to show")).toBeVisible();
  await page.getByLabel("Type matching").selectOption("any");
  await page.getByLabel("Attack minimum").fill("50");
  await expect(page.getByText("No Pokémon to show")).toBeVisible();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await expect(page.getByRole("article")).toHaveCount(12);
  await page.getByRole("button", { name: "Add bulbasaur to team" }).click();
  await page.getByLabel("Team name", { exact: true }).fill("Profile lineup");
  await page.getByRole("button", { name: "Save team", exact: true }).click();
  await expect(page.getByText("Team saved.", { exact: true })).toBeVisible();
  // Opening the profile keeps an unsaved builder draft in memory.
  await page.getByRole("button", { name: "Add charmander to team" }).click();
  await page.getByRole("button", { name: "Profile", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Profile", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Edit Profile lineup" })).toBeVisible();
  await page.getByLabel("Username", { exact: true }).fill(`${username}_n`);
  await page.getByLabel("Current password").fill(password);
  await page.getByRole("button", { name: "Save account" }).click();
  await expect(page.getByText("Account updated.")).toBeVisible();
  await page.getByRole("button", { name: "Back to Pokédex" }).click();
  await expect(page.getByRole("button", { name: "Remove charmander from slot 2" })).toBeVisible();
  await page.getByRole("button", { name: "Save team", exact: true }).click();
  await expect(page.getByText("Team saved.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Profile", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("profile-mobile.png"), fullPage: true });
  await page.getByLabel("New password", { exact: true }).fill("Updated-ux-password-2026");
  await page.getByLabel("Current password").fill(password);
  await page.getByRole("button", { name: "Save account" }).click();
  await expect(page.getByLabel("Password", { exact: true })).toBeVisible();
  await page.getByLabel("Username").fill(`${username}_n`);
  await page.getByLabel("Password", { exact: true }).fill("Updated-ux-password-2026");
  await page.locator("form").getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Profile", exact: true }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Delete Profile lineup" }).click();
  await expect(page.getByText("No saved teams.")).toBeVisible();
});
