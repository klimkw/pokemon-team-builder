import { expect, test } from "@playwright/test";
import { signInFreshAccount } from "./helpers";

test('save and reload a duplicate-friendly lineup, then persist a reorder', async ({ page }) => {
  await signInFreshAccount(page);
  const add = page.getByRole('button', { name: 'Add bulbasaur to team' });
  await add.click();
  await add.click();
  await page.getByRole('button', { name: 'Add charmander to team' }).click();
  for (let i = 0; i < 3; i++) await add.click();
  await expect(add).toBeDisabled();
  await page.getByLabel('Team name', { exact: true }).fill('First lineup');
  await page.getByRole('button', { name: 'Save team', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Team saved.', exact: true })).toBeDisabled();
  await page.reload();
  await expect(page.getByLabel('Team name', { exact: true })).toHaveValue('First lineup');
  await page.getByRole('button', { name: 'Move charmander in slot 3 up' }).click();
  await page.getByRole('button', { name: 'Remove bulbasaur from slot 3' }).click();
  await page.getByLabel('Team name', { exact: true }).fill('Edited lineup');
  await page.getByRole('button', { name: 'Save team', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Team saved.', exact: true })).toBeDisabled();
  await page.reload();
  const teams = await (await page.request.get('/api/teams')).json();
  expect(teams).toHaveLength(1);
  expect(teams[0].name).toBe('Edited lineup');
  expect(teams[0].members.map((m: { pokemon: { id: number } }) => m.pokemon.id)).toEqual([1, 4, 1, 1, 1]);
  await expect(page.getByRole('button', { name: 'Remove charmander from slot 2' })).toBeVisible();
});

test('cancelled switching retains a draft and deleting a saved team preserves the other', async ({ page }) => {
  await signInFreshAccount(page);
  const created = await page.request.post('/api/teams', { data: { name: 'Existing', pokemon_ids: [1] } });
  expect(created.status()).toBe(201);
  const team = await created.json();
  await page.reload();
  await page.getByLabel('Saved teams').selectOption('');
  await page.getByLabel('Team name', { exact: true }).fill('Empty lineup');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByLabel('Saved teams').selectOption(team.id);
  await expect(page.getByLabel('Team name', { exact: true })).toHaveValue('Empty lineup');
  await page.getByRole('button', { name: 'Save team', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Team saved.', exact: true })).toBeDisabled();
  await page.getByLabel('Saved teams').selectOption(team.id);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete team', exact: true }).click();
  await expect(page.getByText('Team deleted.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Team name', { exact: true })).toHaveValue('Empty lineup');
  const remaining = await (await page.request.get('/api/teams')).json();
  expect(remaining).toHaveLength(1);
  expect(remaining[0].name).toBe('Empty lineup');
  expect(remaining[0].members).toEqual([]);
});
